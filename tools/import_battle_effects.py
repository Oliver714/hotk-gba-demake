"""Convert the generated effects atlas into small, aligned GBA sprites."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
source = Image.open(ROOT / 'assets/effects/battle-effects-v1.png').convert('RGBA')
width, height = source.size
# The generated atlas has slightly different row heights; these boundaries
# separate the eight effects without including their neighboring effects.
bounds = (0, 211, 378, 522, 728, 885, 1070, 1254, 1456)
sizes = ((48, 32), (32, 42), (24, 18), (32, 48),
         (48, 32), (40, 42), (48, 32), (40, 40))
sprites = []
for row, size in enumerate(sizes):
    frames = []
    for col in range(3):
        cell = source.crop((col*width//3, bounds[row]*height//1456,
                            (col+1)*width//3, bounds[row+1]*height//1456))
        # Ignore faint edge noise when finding the useful extent.
        alpha = cell.getchannel('A').point(lambda value: 255 if value >= 160 else 0)
        box = alpha.getbbox()
        frames.append(cell.crop(box) if box else cell)
    max_w = max(frame.width for frame in frames)
    max_h = max(frame.height for frame in frames)
    for frame in frames:
        resized = frame.resize((max(1, round(frame.width*size[0]/max_w)),
                                max(1, round(frame.height*size[1]/max_h))), Image.LANCZOS)
        canvas = Image.new('RGBA', (48, 48))
        canvas.paste(resized, ((48-resized.width)//2, 48-resized.height))
        sprites.append(canvas)

sheet = Image.new('RGB', (48*3, 48*8))
alpha_sheet = Image.new('L', sheet.size)
for index, sprite in enumerate(sprites):
    point = (index%3*48, index//3*48)
    sheet.paste(sprite.convert('RGB'), point)
    alpha_sheet.paste(sprite.getchannel('A'), point)
indexed = sheet.quantize(colors=48, method=Image.MEDIANCUT,
                         dither=Image.NONE)
palette = indexed.getpalette()[:48*3]
out = ROOT / 'generated'
(out/'effect_palette.inc').write_text('\n'.join(
    'bn::color('+','.join(str(round(c*31/255)) for c in palette[i:i+3])+'),' 
    for i in range(0, len(palette), 3))+'\n', encoding='ascii')
lines = ['// Generated by tools/import_battle_effects.py.', '#include "battle_effects.h"',
         'namespace sg {', 'alignas(4) const uint8_t battle_effects[8][3][48*48] = {']
preview = Image.new('RGBA', sheet.size)
for row in range(8):
    lines.append('{')
    for col in range(3):
        data=[]
        for y in range(48):
            for x in range(48):
                point=(col*48+x, row*48+y)
                index=indexed.getpixel(point)
                opaque=alpha_sheet.getpixel(point)>=160
                data.append(118+index if opaque else 0)
                if opaque: preview.putpixel(point, tuple(palette[index*3:index*3+3])+(255,))
        lines.append('{'+','.join(map(str,data))+'},')
    lines.append('},')
lines.extend(['};', '}'])
(out/'battle_effects.cpp').write_text('\n'.join(lines)+'\n',encoding='ascii')
preview.save(ROOT/'assets/effects/battle-effects-gba.png')
print('Imported 8 effects, 3 frames each, 48x48, 48 shared colors.')
