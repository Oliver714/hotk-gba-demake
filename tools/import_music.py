"""Compress complete user music once; runtime volume needs no ROM duplicates."""
from pathlib import Path
from array import array
import hashlib,json,math,shutil,struct,subprocess,sys,wave
from adpcm_codec import encode,decode,transition,SAMPLES,BYTES
ROOT=Path(__file__).resolve().parents[1]
def ffmpeg():
    binary=shutil.which('ffmpeg')
    if binary: return binary
    try:
        import imageio_ffmpeg
        return imageio_ffmpeg.get_ffmpeg_exe()
    except ImportError:
        raise SystemExit('Install ffmpeg or run: python -m pip install imageio-ffmpeg')
RATE=16777216/1056
manifest={'codec':'IMA4 independent512 blocks','sample_rate':RATE,'timer_divisor':1056,'tracks':{}}
assembly=['.section .rodata.music_adpcm,"a",%progbits']
metadata=['// Generated by tools/import_music.py.','#include "music_adpcm.h"','namespace sg::audio {']
for name,file in [('world','主游戏.mp3'),('battle','战斗.mp3')]:
    source=ROOT/'audio_design'/file
    result=subprocess.run([ffmpeg(),'-v','error','-i',str(source),'-vn','-ac','1','-ar','15888','-f','s16le','-'],capture_output=True,check=True)
    samples=array('h'); samples.frombytes(result.stdout)
    if sys.byteorder!='little': samples.byteswap()
    peak=max(abs(v) for v in samples); rms=math.sqrt(sum(v*v for v in samples)/len(samples))
    gain=min(28160/peak,7680/max(1,rms))
    # Preserve pitch/time. At most32ms of silence aligns the last block.
    edge=round(RATE*.012)
    pcm=[max(-32768,min(32767,round(v*gain*min(1,i/edge,(len(samples)-1-i)/edge)))) for i,v in enumerate(samples)]
    pcm += [0]*((-len(pcm))%SAMPLES)
    compressed=encode(pcm); restored=decode(compressed)
    error=sum((a-b)**2 for a,b in zip(pcm,restored))
    snr=10*math.log10(sum(v*v for v in pcm)/max(1,error))
    filename=f'music_{name}.adpcm'; symbol=f'music_{name}_adpcm'
    (ROOT/'generated'/filename).write_bytes(compressed)
    assembly+=['.balign 4',f'.global {symbol}',f'.type {symbol}, %object',symbol+':',f'.incbin "../generated/{filename}"',f'.size {symbol}, .-{symbol}']
    metadata.append(f'extern "C" const uint8_t {symbol}[];')
    metadata.append(f'const AdpcmTrack {name}_music={{{symbol},{len(pcm)//SAMPLES}}};')
    with wave.open(str(ROOT/'audio_design'/(name+'-adpcm-preview.wav')),'wb') as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(round(RATE)); w.writeframes(struct.pack('<'+'h'*len(restored),*restored))
    manifest['tracks'][name]={'source':file,'source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),
        'decoded_seconds':len(samples)/15888,'playback_seconds':len(pcm)/RATE,'samples':len(pcm),'blocks':len(pcm)//SAMPLES,
        'compressed_bytes':len(compressed),'snr_db':snr,'gain':gain,'decoder_warnings':result.stderr.decode('utf-8',errors='replace')}
metadata.append('const uint32_t adpcm_transitions[89*16]={')
for index in range(89):
    metadata.append(','.join(hex((delta&0xffffff)|(next_index<<24)) for delta,next_index in (transition(index,code) for code in range(16)))+',')
metadata+=['};','}']
assembly.append('.section .note.GNU-stack,"",%progbits')
(ROOT/'generated/music_adpcm_data.s').write_text('\n'.join(assembly)+'\n',encoding='ascii')
(ROOT/'generated/music_adpcm.cpp').write_text('\n'.join(metadata)+'\n',encoding='ascii')
(ROOT/'generated/music_manifest.json').write_text(json.dumps(manifest,indent=2,ensure_ascii=False),encoding='utf-8')
print(json.dumps(manifest,indent=2,ensure_ascii=False))
