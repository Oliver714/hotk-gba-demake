"""Precompile transparent sprite spans for each pose, direction and x alignment."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / 'generated/battle_sprites.cpp').read_text(encoding='utf-8')
lines = ['// Generated by tools/import_packed_sprites.py.', '#include "packed_sprites.h"',
         'namespace sg {', 'namespace {']


def compile_sprite(kind, dimensions, width, height):
    match = re.search(r'const uint8_t ' + kind + r'_sprites[^=]*= (.*?);', source, re.S)
    if not match:
        raise ValueError(f'Missing {kind} sprite array')
    data = list(map(int, re.findall(r'\d+', match.group(1))))
    expected = 1
    for size in dimensions:
        expected *= size
    expected *= width * height
    if len(data) != expected:
        raise ValueError(f'Unexpected {kind} sprite shape: {len(data)} values, expected {expected}')

    # Recursive construction preserves the declared C array shape while each
    # leaf is a sprite represented by two directions and four x phases.
    def build(level, prefix):
        if level < len(dimensions):
            children = [build(level + 1, prefix + [index]) for index in range(dimensions[level])]
            return '{' + ','.join(children) + '}'
        flat_index = 0
        for index, size in zip(prefix, dimensions):
            flat_index = flat_index * size + index
        pixels = data[flat_index * width * height:(flat_index + 1) * width * height]
        directions = []
        for flip in range(2):
            row_phases = []
            flipped = []
            for y in range(height):
                row = pixels[y * width:(y + 1) * width]
                flipped.extend(row[::-1] if flip else row)
            for phase in range(4):
                name = kind + '_' + '_'.join(map(str, prefix)) + f'_{flip}_{phase}'
                spans = []
                offsets = [0]
                for y in range(height):
                    row = flipped[y * width:(y + 1) * width]
                    row = [0] * phase + row
                    row += [0] * ((-len(row)) % 4)
                    for x in range(0, len(row), 4):
                        group = row[x:x + 4]
                        value = sum(color << (i * 8) for i, color in enumerate(group))
                        if value:
                            mask = sum(255 << (i * 8) for i, color in enumerate(group) if color)
                            spans.append(f'{{{value}u,{mask}u,{x}u}}')
                    offsets.append(len(spans))
                lines.append(f'const SpriteSpan {name}_spans[]={{' + ','.join(spans) + '};')
                lines.append(f'const uint16_t {name}_rows[]={{' + ','.join(map(str, offsets)) + '};')
                row_phases.append(f'{{{name}_spans,{name}_rows,{height}}}')
            directions.append('{' + ','.join(row_phases) + '}')
        return '{' + ','.join(directions) + '}'

    initializer = build(0, [])
    shape = '[' + ']['.join(map(str, dimensions + [2, 4])) + ']'
    return f'const PackedSprite packed_{kind}{shape}={initializer};'


cavalry_table = compile_sprite('cavalry', [2, 7], 56, 48)
lines.extend(['}', cavalry_table])
lines.append(compile_sprite('infantry', [2, 4, 5], 28, 30))
lines.append('}')
(ROOT / 'generated/packed_sprites.cpp').write_text('\n'.join(lines) + '\n', encoding='ascii')
print('Compiled aligned transparent spans for all cavalry and infantry poses.')
