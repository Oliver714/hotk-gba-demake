"""Compile small battle poses into ROM; no runtime resizing or extra RAM."""
from pathlib import Path
from collections import Counter
import re
ROOT=Path(__file__).resolve().parents[1]
source=(ROOT/'generated/battle_sprites.cpp').read_text(encoding='utf-8')
lines=['// Generated by tools/import_zoom_sprites.py.','#include "zoom_sprites.h"','#include "packed_sprites.h"','namespace sg {','namespace {']
tables={}
packed_tables=[]
for kind,dims,w,h in [('cavalry',(2,7),56,48),('infantry',(2,4,5),28,30)]:
    match=re.search(r'const uint8_t '+kind+r'_sprites[^=]*= (.*?);',source,re.S)
    pixels=list(map(int,re.findall(r'\d+',match[1])))
    tables[kind]=[]
    for shift in range(1,6):
        factor=1<<shift; sw=(w+factor-1)//factor; sh=(h+factor-1)//factor
        packed_leaves=[]
        def build(level,indices):
            if level<len(dims):
                return '{'+','.join(build(level+1,indices+[i]) for i in range(dims[level]))+'}'
            flat=0
            for i,n in zip(indices,dims): flat=flat*n+i
            pose=pixels[flat*w*h:(flat+1)*w*h]
            result=[]
            for y in range(sh):
                for x in range(sw):
                    block=[pose[yy*w+xx] for yy in range(y*factor,min(h,(y+1)*factor)) for xx in range(x*factor,min(w,(x+1)*factor))]
                    center=pose[min(h-1,y*factor+factor//2)*w+min(w-1,x*factor+factor//2)]
                    visible=[p for p in block if p]
                    result.append(center or (Counter(visible).most_common(1)[0][0] if visible else 0))
            name=f'{kind}_{shift}_'+ '_'.join(map(str,indices))
            lines.append(f'const uint8_t {name}[]={{'+','.join(map(str,result))+'};')
            # Only the common half-size infantry path pays for packed spans.
            # Packing all five sizes would cross the 4 MiB cartridge boundary.
            if kind=='infantry' and shift==1:
                directions=[]
                for flip in range(2):
                    phases=[]
                    for phase in range(4):
                        spans=[]; offsets=[0]
                        for yy in range(sh):
                            row=result[yy*sw:(yy+1)*sw]
                            row=[0]*phase+(row[::-1] if flip else row)
                            row += [0]*((-len(row))%4)
                            for xx in range(0,len(row),4):
                                group=row[xx:xx+4]
                                value=sum(c<<(k*8) for k,c in enumerate(group))
                                if value:
                                    mask=sum(255<<(k*8) for k,c in enumerate(group) if c)
                                    spans.append(f'{{{value}u,{mask}u,{xx}u}}')
                            offsets.append(len(spans))
                        tag=f'{name}_packed_{flip}_{phase}'
                        lines.append(f'const SpriteSpan {tag}_spans[]={{'+','.join(spans)+'};')
                        lines.append(f'const uint16_t {tag}_rows[]={{'+','.join(map(str,offsets))+'};')
                        phases.append('{'+f'{tag}_spans,{tag}_rows,{sh}'+'}')
                    directions.append('{'+','.join(phases)+'}')
                packed_leaves.append('{'+','.join(directions)+'}')
            return '{'+f'{name},{sw},{sh}'+'}'
        tables[kind].append(build(0,[]))
        if kind=='infantry' and shift==1:
            leaf=iter(packed_leaves)
            def packed_shape(level):
                return next(leaf) if level==len(dims) else '{'+','.join(packed_shape(level+1) for _ in range(dims[level]))+'}'
            packed_tables.append(packed_shape(0))
lines.append('}')
lines.append('const PackedSprite packed_zoom_infantry[2][4][5][2][4]='+packed_tables[0]+';')
for kind,dims,w,h in [('cavalry',(2,7),56,48),('infantry',(2,4,5),28,30)]:
    shape='[5]'+''.join(f'[{n}]' for n in dims)
    lines.append(f'const ZoomSprite zoom_{kind}{shape}={{'+','.join(tables[kind])+'};')
lines.append('}')
(ROOT/'generated/zoom_sprites.cpp').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('Compiled five small-pose scales into ROM')
